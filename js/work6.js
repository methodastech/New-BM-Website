/* 26 Oct 2026: a case film with data-loop-from plays its opening when it comes into view, then loops only the part
   after that second; one with data-play-once (Breadly Made's delivery mascot walking in) plays and rests on its last
   frame. Scrolled away, either rests and starts over the next time it is seen. */
(function(){
  var vs=document.querySelectorAll('video[data-loop-from],video[data-play-once]');
  if(!vs.length) return;
  vs.forEach(function(v){
    if(!v.hasAttribute('data-loop-from')) return;
    var from=parseFloat(v.getAttribute('data-loop-from'))||0;
    v.addEventListener('ended',function(){v.currentTime=from;v.play().catch(function(){})});
  });
  if(!('IntersectionObserver' in window)){vs.forEach(function(v){v.play().catch(function(){})});return}
  var io=new IntersectionObserver(function(es){es.forEach(function(e){
    var v=e.target;
    if(e.isIntersecting){ if(v.paused&&!v._seen){v._seen=1;v.currentTime=0;v.play().catch(function(){})} }
    else { v._seen=0; if(!v.paused) v.pause() }
  })},{threshold:.5});
  vs.forEach(function(v){io.observe(v)});
})();
