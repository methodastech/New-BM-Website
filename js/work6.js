  navb(); window.addEventListener('scroll',navb,{passive:true}); window.addEventListener('resize',navb); window.addEventListener('load',navb);
  /* the nav moves when the admin bar lands and changes height when it turns .scrolled */
  var nv=document.getElementById('nav');
  if(nv){ if(window.ResizeObserver) new ResizeObserver(navb).observe(nv); new MutationObserver(navb).observe(nv,{attributes:true,attributeFilter:['class','style']}); }
  [300,1200,3000].forEach(function(t){setTimeout(navb,t)});
  window.addEventListener('hashchange',function(){setTimeout(navb,60);document.querySelectorAll('.wk6-about.is-open').forEach(close)});
