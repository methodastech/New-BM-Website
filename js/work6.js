/* 6 Oct 2026: Work grid. With a filter or a search on, the wide and narrow pairs
   fall back to equal tiles (.is-filtered), so no project is left hanging. */
(function(){
  var g=document.getElementById('wkgrid');
  if(!g||!g.classList.contains('wk6-grid')) return;
  var s=document.getElementById('wkSearch');
  function sync(){
    var on=document.querySelector('#pg-work .wk-chip.on');
    var f=on?on.getAttribute('data-filter'):'all';
    g.classList.toggle('is-filtered',f!=='all'||!!(s&&s.value.trim()));
  }
  /* 7 Oct 2026: the "More of the work" tile takes the columns the last row leaves empty, and hides when the row is full */
  var more=document.getElementById('wkMore');
  function fill(){
    if(!more) return;
    var cols=getComputedStyle(g).gridTemplateColumns.split(' ').filter(Boolean).length||1;
    var n=g.querySelectorAll('.wk6:not(.hide)').length, rem=n%cols;
    more.hidden=!n||!rem||cols<2;
    more.style.gridColumn=rem?'span '+(cols-rem):'';
    more.classList.toggle('is-wide',cols-rem>1);
  }
  function both(){sync();fill()}
  document.querySelectorAll('#pg-work .wk-chip').forEach(function(c){c.addEventListener('click',function(){setTimeout(both,0)})});
  if(s) s.addEventListener('input',function(){setTimeout(both,0)});
  window.addEventListener('resize',fill);
  fill();
})();

